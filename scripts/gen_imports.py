def stack_bytes(full):
    dll, sym = full.split("!", 1)
    if full in ARGC:
        return ARGC[full] * 4
    m = re.fullmatch(r"_?(\w+)@(\d+)", sym)
    if m:
        return int(m.group(2))
    if sym not in ARGC:
        raise SystemExit(f"no argument count for {full}: add it to ARGC")
    n = ARGC[sym]
    return -1 if n < 0 else n * 4


def c_ident(full):
    dll, sym = full.split("!", 1)
    sym = re.sub(r"@\d+$", "", sym).lstrip("_")
    return sym if not sym.startswith("#") else dll.split(".")[0] + "_ord" + sym[1:]


def main(src, dst):
    imports = json.load(open(src))["kernel_imports"]
    rows = []
    for i in imports:
        rows.append((int(i["thunk_addr"], 16), i["name"], stack_bytes(i["name"]), c_ident(i["name"])))
    with open(dst, "w") as f:
        f.write("/* Generated by scripts/gen_imports.py from gta2_analysis.json. Do not edit. */\n")
        f.write('#include "winapi/imports.h"\n\n')
        f.write(f"const ImportEntry g_import_table[{len(rows)}] = {{\n")
        for va, name, nb, ident in rows:
            f.write(f'    {{ 0x{va:08X}u, "{name}", "{ident}", {nb} }},\n')
        f.write("};\n")
        f.write(f"const unsigned g_import_count = {len(rows)};\n")
    print(f"{dst}: {len(rows)} imports")


if __name__ == "__main__":
    main(*sys.argv[1:3])
