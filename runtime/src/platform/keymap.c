uint8_t g_key_down[256]; /* indexed by DirectInput scan code */

int keymap_from_mac(unsigned mac, uint8_t *vk, uint8_t *dik)
{
    for (unsigned i = 0; i < sizeof g_map / sizeof *g_map; i++) {
        if (g_map[i].mac == mac) {
            *vk = g_map[i].vk;
            *dik = g_map[i].dik;
            return 1;
        }
    }
    return 0;
}
